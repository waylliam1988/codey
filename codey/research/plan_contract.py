"""Compact plan input; original spans and legacy report accounting are derived.

Numbered lines are a conservative structural default, not a semantic classifier.
All other text remains explicit task context. The original accounting ids remain
internal provenance, so old report admission and old frozen requests still work.
"""

from __future__ import annotations

import hashlib
import json
import re
from dataclasses import replace
from typing import Any

from codey.research.knowledge_schema import array_schema, object_schema
from codey.research.questions import question_plan
from codey.research.task_requirements import coverage_requirements, report_requirements

_NUMBERED = re.compile(r"(?m)^[ \t]*([1-9][0-9]*)[.)、．][ \t]*([^\r\n]+)")
_CONTINUATION = re.compile(r"\r?\n[ \t]+(?![1-9][0-9]*[.)、．])\S[^\r\n]*")


def task_layout(task: str) -> dict[str, Any]:
    matches = list(_NUMBERED.finditer(task))
    numbered = (2 <= len(matches) <= 8 and [int(row[1]) for row in matches] == list(range(1, len(matches) + 1)))
    spans = []
    if numbered:
        for index, row in enumerate(matches):
            end = row.end(2)
            limit = matches[index + 1].start() if index + 1 < len(matches) else len(task)
            while continuation := _CONTINUATION.match(task, end, limit):
                end = continuation.end()
            spans.append((row.start(2), end))
    else:
        spans = [(0, len(task))]
    questions = [{"task_ref": f"t{index}", "start": start, "end": end, "text": task[start:end]}
                 for index, (start, end) in enumerate(spans, 1)]
    context = []
    start = 0
    for begin, end in spans:
        if begin > start:
            context.append({"start": start, "end": begin, "text": task[start:begin]})
        start = end
    if start < len(task):
        context.append({"start": start, "end": len(task), "text": task[start:]})
    return {"task_questions": questions, "other_task_context": context,
            "report_requirements_checked_by_application": report_requirements(task),
            "interpretation": "Structural defaults only. Other task context remains binding; no semantic coverage is certified."}


def compact_plan_spec(spec: Any, task: str) -> Any:
    question = object_schema({"text": {"type": "string", "minLength": 1, "maxLength": 800},
        "task_refs": {**array_schema({"type": "string"}), "minItems": 1,
                      "description": "Original tN question spans addressed by this complete question."},
        "work_units": {"type": "array", "minItems": 1, "maxItems": 4,
                       "items": {"type": "string", "minLength": 1, "maxLength": 800},
                       "description": "Optional only when necessary; keep full OR conditions, negations and exceptions together."}},
        "text", "task_refs")
    schema = object_schema({"questions": {"type": "array", "minItems": 1, "maxItems": 8, "items": question},
                            "contract_version": {"type": "integer", "enum": [4],
                                                 "description": "Fixed by the application; may be omitted."}})
    defaults = task_layout(task)["task_questions"]
    example_args: dict[str, Any] = {} if all(1 <= len(row["text"].strip()) <= 800 for row in defaults) else {
        "questions": [{"text": "The complete requested relationship and its evidence boundary", "task_refs": ["t1"]}]}
    return replace(spec, parameters=tuple(schema["properties"].items()), required=(),
        json_examples=(json.dumps({"tool": "research_plan", "args": example_args}, separators=(",", ":")),),
        description="Register the task's complete questions once. Call with {} to use the original task_questions "
                    "without copying them. Only if grouping needs adjustment, supply one questions array of "
                    "{text,task_refs,optional work_units}; cover all original tN spans and retain other task context. "
                    "Question ids and report accounting are generated by the application. "
                    "Do not turn numbering, source interfaces or report instructions into extra research questions. "
                    "Registration is not evidence or semantic verification.")


def is_compact_plan_spec(spec: Any) -> bool:
    if spec is None:
        return False
    kind = dict(spec.parameters).get("questions", {}).get("items", {}).get("type")
    return isinstance(kind, str) and kind == "object"


def frozen_plan_version(spec: Any) -> int:
    version = dict(spec.parameters).get("contract_version", {}).get("enum", [2])
    if tuple(version) not in ((2,), (3,), (4,)) or type(version[0]) is not int:
        raise ValueError("invalid frozen plan entry version")
    result: int = version[0]
    return result


def _accounting_ranges(layout: dict[str, Any], task: str, refs: list[str]) -> list[dict[str, int]]:
    """Own numbering locally; only nonblank global text binds every question."""
    prefixes = {match.start(2): match.start() for match in _NUMBERED.finditer(task)}
    questions = [{"start": prefixes.get(row["start"], row["start"]), "end": row["end"],
                  "task_ref": row["task_ref"]} for row in layout["task_questions"]]
    ranges = [{"start": row["start"], "end": row["end"]} for row in questions if row["task_ref"] in refs]
    start = 0
    for row in [*questions, {"start": len(task), "end": len(task)}]:
        text = task[start:row["start"]]
        if text.strip():
            ranges.append({"start": start + len(text) - len(text.lstrip()),
                           "end": row["start"] - len(text) + len(text.rstrip())})
        start = row["end"]
    return ranges


def compact_plan(raw: object, task: str, *, submission_mode: str = "select", schema_version: int = 3) -> dict[str, Any]:
    if type(schema_version) is not int or schema_version not in (2, 3):
        raise ValueError("invalid compact plan accounting version")
    layout = task_layout(task)
    original = {row["task_ref"]: row for row in layout["task_questions"]}
    if raw is None:
        raw = [{"text": row["text"], "task_refs": [row["task_ref"]]} for row in original.values()]
    if not isinstance(raw, list) or not 1 <= len(raw) <= 8:
        raise ValueError("questions requires 1..8 objects; use {} for the original complete questions")
    rows = []
    seen = set()
    accounting = coverage_requirements(task)
    for row in raw:
        if (not isinstance(row, dict) or not {"text", "task_refs"} <= set(row)
                or set(row) - {"text", "task_refs", "work_units"}):
            raise ValueError("each question requires text and original tN task_refs, with optional work_units")
        refs = row["task_refs"]
        if (not isinstance(refs, list) or not refs or any(not isinstance(ref, str) for ref in refs)
                or len(refs) != len(set(refs)) or not set(refs) <= original.keys()):
            raise ValueError("task_refs must select exact original tN question spans")
        spans = [original[ref] for ref in refs]
        # Retain all non-question context as binding provenance. This is not a
        # claim that the model has answered a source-interface or format rule.
        ranges = ([*spans, *layout["other_task_context"]] if schema_version == 2
                  else _accounting_ranges(layout, task, refs))
        task_refs = [unit["task_ref"] for unit in accounting
                     if any(unit["start"] < span["end"] and span["start"] < unit["end"] for span in ranges)]
        item = {"text": row["text"], "task_spans": refs, "task_refs": task_refs}
        if "work_units" in row:
            units = row["work_units"]
            if (not isinstance(units, list) or not 1 <= len(units) <= 4
                    or any(not isinstance(unit, str) or not 1 <= len(unit.strip()) <= 800 for unit in units)
                    or len(set(units)) != len(units)):
                raise ValueError("work_units requires 1..4 distinct complete relationship targets")
            item["work_units"] = list(units)
        rows.append(item)
        seen.update(refs)
    question_plan([row["text"] for row in rows])
    if seen != original.keys():
        raise ValueError("questions must retain every original task span; missing: " + ", ".join(sorted(original.keys() - seen)))
    return {"schema_version": schema_version, "questions": rows, "task_layout": layout,
            "task_sha256": hashlib.sha256(task.encode()).hexdigest(), "submission_mode": submission_mode}


def validate_compact_plan(plan: dict[str, Any], task: str) -> tuple[str, ...]:
    if (set(plan) != {"schema_version", "questions", "task_layout", "task_sha256", "submission_mode"}
            or type(plan["schema_version"]) is not int or plan["schema_version"] not in (2, 3)):
        raise ValueError("invalid compact plan observation")
    if plan["submission_mode"] not in {"select", "inline"}:
        raise ValueError("invalid frozen submission contract")
    if (not isinstance(plan["questions"], list) or any(not isinstance(row, dict)
            or not {"text", "task_spans", "task_refs"} <= set(row)
            or set(row) - {"text", "task_spans", "task_refs", "work_units"} for row in plan["questions"])):
        raise ValueError("invalid compact plan question objects")
    raw = [{"text": row["text"], "task_refs": row["task_spans"],
            **({"work_units": row["work_units"]} if "work_units" in row else {})} for row in plan["questions"]]
    if compact_plan(raw, task, submission_mode=plan["submission_mode"], schema_version=plan["schema_version"]) != plan:
        raise ValueError("compact plan differs from its original task spans")
    return question_plan([row["text"] for row in plan["questions"]])
