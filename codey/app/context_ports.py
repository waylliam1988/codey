"""Consumer-owned application resources used beneath context assembly."""
from __future__ import annotations

import threading
from collections import OrderedDict
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Protocol

from codey.app.input_queue import DurableConversationInputQueue
from codey.app.provider_registry import ProviderRegistry
from codey.app.run_registry import RunRegistry, RunSnapshot
from codey.app.shell_approval_coordinator import ShellApprovalCoordinator
from codey.app.task_lifecycle import TaskLifecycleCoordinator
from codey.app.task_runtime import TaskRuntimeCoordinator
from codey.app.task_state import AppTaskState
from codey.durable.questions import DurableUserQuestionStore
from codey.durable.scheduler import DurableTaskScheduler
from codey.durable.session import DurableSession
from codey.runs.ledger import RunLedgerStore
from codey.runtime.effects.shell_approval_records import ShellApprovalFact, ShellApprovalRecordStore
from codey.storage.command_permissions import CommandPermissionStore
from codey.storage.execution_output_store import ExecutionOutputStore
from codey.storage.managed_outputs import ManagedOutputStore
from codey.storage.ui_state_store import UiStateStore
from codey.workspace.changes import ChangeTracker, SnapshotStore


class DurableContext(Protocol):
    @property
    def durable(self) -> DurableSession: ...


class ConversationStoreContext(DurableContext, Protocol):
    @property
    def ui_state_store(self) -> UiStateStore: ...
    @property
    def ui_state_store_lock(self) -> threading.Lock: ...
    def emit(self, event: Mapping[str, object]) -> None: ...
    def load_ui_state(self) -> dict[str, object]: ...


class RunContext(Protocol):
    @property
    def run_registry(self) -> RunRegistry: ...
    def active_run_for(self, *, session_id: str = "", project: str | None = None) -> RunSnapshot | None: ...
    def stop_flag_for(self, run_id: str) -> threading.Event: ...


class ApprovalStatuses(Protocol):
    def list_statuses(self, *, session_id: str = "") -> Sequence[Mapping[str, object]]: ...


class QueryContext(DurableContext, Protocol):
    @property
    def user_questions(self) -> DurableUserQuestionStore: ...
    @property
    def shell_approval_workflow(self) -> ApprovalStatuses: ...
    @property
    def run_ledgers(self) -> RunLedgerStore | None: ...
    @property
    def execution_outputs(self) -> ExecutionOutputStore: ...
    def active_runs(self) -> tuple[RunSnapshot, ...]: ...


class ControlContext(ConversationStoreContext, QueryContext, RunContext, Protocol):
    @property
    def state_home(self) -> Path | None: ...
    @property
    def durable_scheduler(self) -> DurableTaskScheduler: ...
    @property
    def input_queue(self) -> DurableConversationInputQueue: ...
    @property
    def providers(self) -> ProviderRegistry: ...
    @property
    def task_runtime(self) -> TaskRuntimeCoordinator: ...
    def request_stop(self, run_id: str | None = None) -> None: ...


class ChangeTrackingContext(DurableContext, Protocol):
    @property
    def lock(self) -> threading.Lock: ...
    @property
    def snapshot_store(self) -> SnapshotStore: ...
    @property
    def change_trackers(self) -> OrderedDict[str, ChangeTracker]: ...


class AbortContext(Protocol):
    @property
    def task_runtime(self) -> TaskRuntimeCoordinator: ...
    @property
    def task_lifecycle(self) -> TaskLifecycleCoordinator: ...


class ControlDrainState(Protocol):
    @property
    def draining(self) -> bool: ...


class ApprovalWorkflowContext(AppTaskState, DurableContext, Protocol):
    @property
    def command_permissions(self) -> CommandPermissionStore: ...
    @property
    def control_service(self) -> ControlDrainState | None: ...
    @property
    def managed_outputs(self) -> ManagedOutputStore | None: ...
    @property
    def shell_approval_coordinator(self) -> ShellApprovalCoordinator: ...
    @property
    def shell_approval_records(self) -> ShellApprovalRecordStore: ...
    def record_shell_approval_fact(self, fact: ShellApprovalFact) -> bool: ...
    def record_shell_result(self, event: Mapping[str, object]) -> None: ...
    def emit_browser_event(self, event: dict[str, object]) -> None: ...
    def shutdown_requested(self) -> bool: ...
